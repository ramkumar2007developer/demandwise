"""Synthetic demo dataset generation and loading.

No verified labelled Coimbatore demand data is present in this repository.
Rows and the target column are generated by a documented formula plus noise.
They must not be treated as real-world demand observations.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from ml.features import BUSINESS_TYPES, TARGET_COLUMN

DATASET_HEADER = (
    "# SYNTHETIC DEMO DATASET — not real Coimbatore sales, footfall, or demand.\n"
    "# Target column synthetic_monthly_visits is produced by a generator formula plus noise.\n"
    "# Do not present model outputs trained on this file as validated real-world demand.\n"
)

GENERATOR_VERSION = "synthetic_demand_v1"


def generate_synthetic_dataset(
    n_per_type: int = 120,
    random_state: int = 42,
    min_lat: float = 10.85,
    max_lat: float = 11.20,
    min_lng: float = 76.80,
    max_lng: float = 77.20,
) -> pd.DataFrame:
    """Create a balanced labelled demo table for cafe, hotel, and retail."""
    rng = np.random.default_rng(random_state)
    rows: list[dict] = []
    for business_type in BUSINESS_TYPES:
        latitudes = rng.uniform(min_lat, max_lat, n_per_type)
        longitudes = rng.uniform(min_lng, max_lng, n_per_type)
        budgets = rng.uniform(50_000, 8_000_000, n_per_type)
        floor_areas = rng.uniform(200, 4000, n_per_type)
        competitors = rng.integers(0, 16, n_per_type)
        near_college = rng.integers(0, 2, n_per_type)
        targets = _synthetic_target(
            business_type=business_type,
            budget_inr=budgets,
            floor_area_sqft=floor_areas,
            competitor_count=competitors,
            near_college=near_college,
            latitude=latitudes,
            longitude=longitudes,
            rng=rng,
        )
        for index in range(n_per_type):
            rows.append(
                {
                    "business_type": business_type,
                    "latitude": float(latitudes[index]),
                    "longitude": float(longitudes[index]),
                    "budget_inr": float(budgets[index]),
                    "floor_area_sqft": float(floor_areas[index]),
                    "competitor_count": int(competitors[index]),
                    "near_college": int(near_college[index]),
                    TARGET_COLUMN: float(targets[index]),
                    "label_source": "synthetic_generator",
                    "generator_version": GENERATOR_VERSION,
                }
            )
    return pd.DataFrame(rows)


def _synthetic_target(
    business_type: str,
    budget_inr: np.ndarray,
    floor_area_sqft: np.ndarray,
    competitor_count: np.ndarray,
    near_college: np.ndarray,
    latitude: np.ndarray,
    longitude: np.ndarray,
    rng: np.random.Generator,
) -> np.ndarray:
    base = {"cafe": 720.0, "hotel": 1100.0, "retail": 860.0}[business_type]
    budget_factor = np.log1p(budget_inr) / np.log1p(1_000_000)
    size_factor = np.clip(floor_area_sqft / 1200.0, 0.4, 2.2)
    competition_penalty = 1.0 - (0.035 * competitor_count)
    college_bonus = 1.0 + (0.18 * near_college)
    # Mild spatial pattern so nearby generated points are correlated.
    spatial = 1.0 + 0.08 * np.sin((latitude - 10.85) * 12) + 0.05 * np.cos((longitude - 76.80) * 10)
    noise = rng.normal(0.0, 55.0, size=budget_inr.shape)
    visits = base * budget_factor * size_factor * competition_penalty * college_bonus * spatial + noise
    return np.clip(visits, 80.0, None)


def save_dataset(frame: pd.DataFrame, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(DATASET_HEADER)
        frame.to_csv(handle, index=False)
    return path


def load_dataset(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Dataset file not found: {path}")
    frame = pd.read_csv(path, comment="#")
    if TARGET_COLUMN not in frame.columns:
        raise ValueError(f"Dataset is missing target column {TARGET_COLUMN}.")
    return frame


def ensure_demo_dataset(path: Path, **generate_kwargs) -> pd.DataFrame:
    if path.exists():
        return load_dataset(path)
    frame = generate_synthetic_dataset(**generate_kwargs)
    save_dataset(frame, path)
    return frame
