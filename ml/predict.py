"""Prediction-service functions for the Phase 2 demand model."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import joblib
import pandas as pd

from app.config import get_settings
from ml.features import (
    MODEL_FEATURE_COLUMNS,
    MODEL_MODE,
    MODEL_NAME,
    TARGET_COLUMN,
    TARGET_DEFINITION,
    InvalidFeatureError,
    prepare_model_frame,
)

DEFAULT_LIMITATIONS = [
    "Predictions come from a synthetic-demo model, not validated real-world demand.",
    "The numeric target is synthetic_monthly_visits generated by a formula plus noise.",
    "Do not treat the output as observed footfall, revenue, or an accuracy/confidence score.",
    "Nearby locations in the demo data are spatially correlated, which inflates in-sample fit.",
]


class ModelArtifactMissingError(FileNotFoundError):
    """Raised when the Joblib model file is absent."""


@dataclass
class DemandPredictionResult:
    predicted_synthetic_monthly_visits: float
    model_mode: str
    model_name: str
    target_name: str
    target_definition: str
    dataset_status: str
    feature_names: list[str]
    limitations: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def load_model_bundle(artifact_path: Path | None = None) -> dict[str, Any]:
    settings = get_settings()
    path = Path(artifact_path or settings.ml_artifact_path)
    if not path.exists():
        raise ModelArtifactMissingError(
            f"Trained model file not found: {path}. Run `python -m ml.train` first."
        )
    bundle = joblib.load(path)
    if "pipeline" not in bundle:
        raise ValueError(f"Invalid model artifact at {path}: missing pipeline.")
    return bundle


def predict_demand(
    raw_features: dict[str, Any] | pd.DataFrame,
    artifact_path: Path | None = None,
) -> DemandPredictionResult:
    bundle = load_model_bundle(artifact_path)
    if isinstance(raw_features, pd.DataFrame):
        frame = raw_features
    else:
        frame = pd.DataFrame([raw_features])
    if len(frame) != 1:
        raise InvalidFeatureError("predict_demand currently accepts a single row.")

    prepared = prepare_model_frame(frame)
    stored_columns = bundle.get("model_feature_columns", MODEL_FEATURE_COLUMNS)
    if list(prepared.columns) != list(stored_columns):
        raise InvalidFeatureError(
            "Feature order/name mismatch between inference input and trained model."
        )

    prediction = bundle["pipeline"].predict(prepared)[0]
    return DemandPredictionResult(
        predicted_synthetic_monthly_visits=float(prediction),
        model_mode=str(bundle.get("model_mode", MODEL_MODE)),
        model_name=str(bundle.get("model_name", MODEL_NAME)),
        target_name=str(bundle.get("target_column", TARGET_COLUMN)),
        target_definition=str(bundle.get("target_definition", TARGET_DEFINITION)),
        dataset_status=str(bundle.get("dataset_status", "synthetic_demo")),
        feature_names=list(stored_columns),
        limitations=list(DEFAULT_LIMITATIONS),
    )
